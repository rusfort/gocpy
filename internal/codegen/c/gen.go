// Package c generates C11 (GNU dialect) code from a type-checked Gocpy package.
//
// Layout of the output:
//
//	gocpy_pkg.h     types, globals, prototypes, @inline bodies (shared by all units)
//	<file>.c        one translation unit per .gocpy file (so <file>.yml can set flags)
//	gocpy_support.c fmt helpers and package initialization
//	gocpy_main.c    C entry point (package main only)
package c

import (
	"fmt"
	"go/constant"
	"math"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/rusfort/gocpy/internal/ast"
	"github.com/rusfort/gocpy/internal/token"
	"github.com/rusfort/gocpy/internal/types"
)

// Output is the generated C code.
type Output struct {
	Files map[string]string // file name -> content
	Units []Unit            // translation units to compile
}

// Unit maps a C file to the Gocpy source it came from ("" for generated support code).
type Unit struct {
	CFile  string
	Source string
}

type loopLabels struct {
	brk, cont string
	finDepth  int // len(g.finStack) at loop entry
}

// tryCtx is a try statement with a finally block, while its body or catch
// clauses are being generated. Jumps that leave it go through the finally.
type tryCtx struct {
	fin     string // label of the finally block
	pend    string // int variable: which pending jump to perform after finally
	actions []pendAction
}

type pendAction struct {
	code int
	emit func()
}

type gen struct {
	pkg  *types.Package
	info *types.Info
	pfx  string

	arrays     map[string]*types.Array
	tuples     map[string]*types.Tuple
	fmtHelpers map[string]types.Type
	fmtOrder   []string

	tmp int

	// current output and function state
	w     *strings.Builder
	ind   int
	sig   *types.Signature
	names map[string]int
	taken map[string]bool
	loops []loopLabels
	errs  []string

	excStack   []string  // labels of enclosing exception handlers
	finStack   []*tryCtx // enclosing try statements with finally
	needExcOut bool      // function uses the exception exit label
	needRetv   bool      // function stores its result in _retv (return through finally)

	typeinfos map[string]types.Type
	tiOrder   []string

	needPerr   bool           // function uses gocpy_perr (? operator)
	deferFin   *ast.BlockStmt // synthetic finally of a function with defer
	deferNamed bool           // defers + named results: return assigns them first
	props      []propPending  // ? return paths not yet emitted
	mapKeys    bool           // next iterate() over a map binds keys only
	done       map[string]bool
	tiDone     int // typeinfos emitted so far
	fmtDone    int // fmt helpers emitted so far

	thunks      strings.Builder // goroutine entry thunks (gocpy_support.c)
	thunkProtos strings.Builder
}

// Generate produces C code for pkg.
func Generate(pkg *types.Package, info *types.Info) (*Output, error) {
	g := &gen{
		pkg: pkg, info: info, pfx: pkg.Name + "_",
		arrays: map[string]*types.Array{}, tuples: map[string]*types.Tuple{},
		fmtHelpers: map[string]types.Type{}, typeinfos: map[string]types.Type{},
		done: map[string]bool{},
	}
	out := &Output{Files: map[string]string{}}

	// assign C names to globals and functions
	for _, v := range pkg.Globals {
		v.CName = g.pfx + v.Name()
	}
	for _, f := range pkg.Funcs {
		f.CName = g.funcName(f)
	}

	// 1. function bodies per source file
	inline := &strings.Builder{}
	for _, file := range pkg.Files {
		src := file.Package.File
		body := &strings.Builder{}
		fmt.Fprintf(body, "/* generated by gocpy from %s — do not edit */\n#include \"gocpy_pkg.h\"\n\n", filepath.Base(src))
		for _, v := range pkg.Globals {
			if pkg.FileOf[v] == file {
				fmt.Fprintf(body, "%s %s;\n", g.cType(v.Type()), v.CName)
			}
		}
		for _, fn := range pkg.Funcs { // declaration order, then generic instances
			fd := fn.Decl
			if fd == nil || fd.Body == nil || pkg.FileOf[fn] != file {
				continue
			}
			if fd.Annots.Has("inline") {
				g.funcDef(inline, fn, true)
			} else {
				g.funcDef(body, fn, false)
			}
		}
		name := strings.TrimSuffix(filepath.Base(src), ".gocpy") + ".c"
		out.Files[name] = body.String()
		out.Units = append(out.Units, Unit{CFile: name, Source: src})
	}

	// 2. package init + fmt helpers
	support := &strings.Builder{}
	support.WriteString("/* generated by gocpy — do not edit */\n#include \"gocpy_pkg.h\"\n\n")
	g.initFunc(support)
	// typeinfos, wrappers, itabs and fmt helpers can discover each other
	var tis, fmts strings.Builder
	for g.tiDone < len(g.tiOrder) || g.fmtDone < len(g.fmtOrder) {
		g.typeinfoDefs(&tis)
		g.fmtHelperDefs(&fmts)
	}
	support.WriteString(g.thunks.String())
	support.WriteString(tis.String())
	support.WriteString(fmts.String())
	out.Files["gocpy_support.c"] = support.String()
	out.Units = append(out.Units, Unit{CFile: "gocpy_support.c"})

	if pkg.Name == "main" {
		out.Files["gocpy_main.c"] = "/* generated by gocpy */\n#include \"gocpy_pkg.h\"\n\n" +
			"int main(int argc, char **argv) {\n    gocpy_init(argc, argv);\n    " + g.pfx + "_init();\n    " +
			g.pfx + "main();\n    gocpy_uncaught();\n    return 0;\n}\n"
		out.Units = append(out.Units, Unit{CFile: "gocpy_main.c"})
	}

	// 3. header last: it needs every type discovered while generating bodies
	out.Files["gocpy_pkg.h"] = g.header(inline.String())

	if len(g.errs) > 0 {
		return nil, fmt.Errorf("codegen: %s", strings.Join(g.errs, "\n"))
	}
	return out, nil
}

func (g *gen) errorf(p token.Pos, f string, a ...any) {
	g.errs = append(g.errs, fmt.Sprintf("%s: %s", p, fmt.Sprintf(f, a...)))
}

func (g *gen) newTmp() string {
	g.tmp++
	return fmt.Sprintf("_t%d", g.tmp)
}

func (g *gen) newLabel(kind string) string {
	g.tmp++
	return fmt.Sprintf("%s_%d", kind, g.tmp)
}

// ---------------------------------------------------------------- names

var cReserved = map[string]bool{}

func init() {
	for _, k := range strings.Fields(`auto break case char const continue default do double else enum extern
		float for goto if inline int long register restrict return short signed sizeof static struct switch
		typedef union unsigned void volatile while _Bool _Complex _Imaginary _Alignas _Alignof _Atomic
		_Generic _Noreturn _Static_assert _Thread_local bool true false NULL errno stdin stdout stderr EOF
		main assert offsetof asm typeof alignas alignof noreturn static_assert thread_local`) {
		cReserved[k] = true
	}
}

func cIdent(name string) string {
	if cReserved[name] || strings.HasPrefix(name, "_t") || strings.HasPrefix(name, "gocpy") {
		return name + "_"
	}
	return name
}

var opNames = map[string]string{
	"+": "op_add", "-": "op_sub", "*": "op_mul", "/": "op_div", "%": "op_rem",
	"==": "op_eq", "<": "op_lt", "<<": "op_shl", ">>": "op_shr", "&": "op_and",
	"|": "op_or", "^": "op_xor", "!": "op_not", "[]": "op_index",
}

func (g *gen) funcName(f *types.Func) string {
	if f.Extern != "" {
		return f.Extern
	}
	if f.Export != "" {
		return f.Export
	}
	name := f.Name()
	if op, ok := opNames[name]; ok && f.IsOperator {
		name = op
		if name == "op_sub" && len(f.Sig().Params) == 0 {
			name = "op_neg"
		}
	}
	s := g.pfx
	if f.RecvNamed != nil {
		s += f.RecvNamed.Obj.Name() + "__"
	}
	s += name + f.Suffix
	if f.Overloaded && !f.IsOperator || (f.IsOperator && len(f.RecvNamed.Methods[f.Name()]) > 1) {
		var ps []string
		for _, p := range f.Sig().Params {
			ps = append(ps, g.typeID(p.Type()))
		}
		if len(ps) == 0 {
			ps = []string{"void"}
		}
		s += "__" + strings.Join(ps, "_")
	}
	return s
}

// localName assigns a unique C name for a local variable within a function.
func (g *gen) localName(v *types.Var) string {
	base := cIdent(v.Name())
	if base == "_" {
		base = "_blank"
	}
	if g.taken == nil {
		g.taken = map[string]bool{}
	}
	n := g.names[base]
	name := base
	for {
		if n > 0 {
			name = fmt.Sprintf("%s_%d", base, n)
		}
		if !g.taken[name] {
			break
		}
		n++
	}
	g.names[base] = n + 1
	g.taken[name] = true
	v.CName = name
	return name
}

func (g *gen) varRef(v *types.Var) string {
	if v.CName == "" {
		v.CName = cIdent(v.Name())
	}
	if v.Boxed && !v.Global {
		return "(*" + v.CName + ")"
	}
	return v.CName
}

// ---------------------------------------------------------------- types

func (g *gen) typeID(t types.Type) string {
	switch t := t.(type) {
	case *types.Basic:
		return strings.ReplaceAll(types.Default(t).String(), " ", "_")
	case *types.Named:
		if t == types.ExceptionType {
			return "Exception"
		}
		if t == types.ErrorType {
			return "error"
		}
		if t.Pkg != "" {
			return t.Pkg + "_" + t.Obj.Name()
		}
		return g.pfx + t.Obj.Name()
	case *types.Chan:
		return "c" + g.typeID(t.Elem)
	case *types.Pointer:
		return "p" + g.typeID(t.Elem)
	case *types.Slice:
		return "s" + g.typeID(t.Elem)
	case *types.Array:
		return fmt.Sprintf("a%d%s", t.Len, g.typeID(t.Elem))
	case *types.Tuple:
		var ids []string
		for _, v := range t.Vars {
			ids = append(ids, g.typeID(v.Type()))
		}
		return "T" + strings.Join(ids, "_")
	case *types.Map:
		return "m" + g.typeID(t.Key) + "_" + g.typeID(t.Elem)
	case *types.Interface:
		if len(t.Methods) == 0 {
			return "any"
		}
		return "I" + shortHash(t.String())
	case *types.Signature:
		return "F" + shortHash(g.sigKey(t))
	}
	return "unknown"
}

func (g *gen) cType(t types.Type) string {
	switch t := t.(type) {
	case *types.Basic:
		switch types.Default(t).(*types.Basic).Kind {
		case types.Bool:
			return "bool"
		case types.Int, types.Int64:
			return "int64_t"
		case types.Int8:
			return "int8_t"
		case types.Int16:
			return "int16_t"
		case types.Int32:
			return "int32_t"
		case types.Uint, types.Uint64:
			return "uint64_t"
		case types.Uint8:
			return "uint8_t"
		case types.Uint16:
			return "uint16_t"
		case types.Uint32:
			return "uint32_t"
		case types.Uintptr:
			return "uintptr_t"
		case types.Float32:
			return "float"
		case types.Float64:
			return "double"
		case types.String:
			return "gocpy_string"
		}
	case *types.Named:
		if t == types.ExceptionType {
			return "gocpy_exception*"
		}
		if t.CName != "" {
			return t.CName
		}
		return g.pfx + t.Obj.Name()
	case *types.Chan:
		return "gocpy_chan*"
	case *types.Map:
		return "gocpy_map*"
	case *types.Interface:
		return "gocpy_iface"
	case *types.Signature:
		return "gocpy_func"
	case *types.Pointer:
		return g.cType(t.Elem) + "*"
	case *types.Slice:
		return "gocpy_slice"
	case *types.Array:
		id := g.typeID(t)
		g.arrays[id] = t
		return "gocpy_arr_" + id
	case *types.Tuple:
		id := g.typeID(t)
		g.tuples[id] = t
		return "gocpy_tup_" + id
	}
	return "void /* unsupported " + t.String() + " */"
}

func (g *gen) zero(t types.Type) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.IsBoolean():
			return "false"
		case u.IsString():
			return "((gocpy_string){0})"
		}
		if _, named := t.(*types.Named); named {
			return "((" + g.cType(t) + ")0)"
		}
		return "0"
	case *types.Pointer, *types.Chan, *types.Map:
		if _, named := t.(*types.Named); named {
			return "((" + g.cType(t) + ")NULL)"
		}
		return "NULL"
	}
	return "((" + g.cType(t) + "){0})"
}

func (g *gen) typeOf(e ast.Expr) types.Type {
	tv, ok := g.info.Types[e]
	if !ok || tv.Type == nil {
		g.errorf(e.Pos(), "internal: no type for expression %T", e)
		return types.Typ[types.Invalid]
	}
	return types.Default(tv.Type)
}

func elemType(t types.Type) types.Type {
	switch u := t.Underlying().(type) {
	case *types.Slice:
		return u.Elem
	case *types.Array:
		return u.Elem
	case *types.Pointer:
		if a, ok := u.Elem.Underlying().(*types.Array); ok {
			return a.Elem
		}
	}
	return nil
}

// ---------------------------------------------------------------- header

func (g *gen) header(inlineBodies string) string {
	var b strings.Builder
	b.WriteString("/* generated by gocpy — do not edit */\n#ifndef GOCPY_PKG_H\n#define GOCPY_PKG_H\n#include \"gocpy_rt.h\"\n\n")

	// prototypes and fmt helpers may discover new tuple/array types: render them first
	var protos strings.Builder
	for _, v := range g.pkg.Globals {
		fmt.Fprintf(&protos, "extern %s %s;\n", g.cType(v.Type()), v.CName)
	}
	protos.WriteString("void " + g.pfx + "_init(void);\n")
	for _, f := range g.pkg.Funcs {
		if f.Decl.Annots.Has("inline") {
			fmt.Fprintf(&protos, "static inline __attribute__((always_inline)) %s;\n", g.signature(f))
		} else {
			fmt.Fprintf(&protos, "%s%s;\n", g.attrs(f), g.signature(f))
		}
	}
	for _, id := range g.tiOrder {
		fmt.Fprintf(&protos, "extern const gocpy_typeinfo gocpy_ti_%s;\n", id)
	}
	protos.WriteString(g.thunkProtos.String())
	for _, id := range g.fmtOrder {
		fmt.Fprintf(&protos, "void gocpy_fmt_%s(gocpy_sb *sb, %s v);\n", id, g.cType(g.fmtHelpers[id]))
	}

	// forward declarations of aggregate types
	for _, n := range g.pkg.Types {
		if _, ok := n.Underlying().(*types.Struct); ok {
			fmt.Fprintf(&b, "typedef struct %s %s;\n", g.cType(n), g.cType(n))
		}
	}
	// make sure array types used by named types are registered
	for _, n := range g.pkg.Types {
		if _, ok := n.Underlying().(*types.Struct); !ok {
			g.cType(n.Underlying())
		}
		if st, ok := n.Underlying().(*types.Struct); ok {
			for _, f := range st.Fields {
				g.cType(f.Type)
			}
		}
	}
	arrIDs := sortedKeys(g.arrays)
	for _, id := range arrIDs {
		fmt.Fprintf(&b, "typedef struct gocpy_arr_%s gocpy_arr_%s;\n", id, id)
	}
	tupIDs := sortedKeys(g.tuples)
	for _, id := range tupIDs {
		fmt.Fprintf(&b, "typedef struct gocpy_tup_%s gocpy_tup_%s;\n", id, id)
	}
	// named non-struct types
	for _, n := range g.pkg.Types {
		if _, ok := n.Underlying().(*types.Struct); !ok {
			fmt.Fprintf(&b, "typedef %s %s;\n", g.cType(n.Underlying()), g.cType(n))
		}
	}
	b.WriteString("\n")

	// full definitions in dependency order (by-value containment)
	type node struct {
		key  string
		deps []string
		def  string
	}
	nodes := map[string]*node{}
	var aggKey func(t types.Type) string
	aggKey = func(t types.Type) string {
		switch x := t.(type) {
		case *types.Named:
			switch x.Underlying().(type) {
			case *types.Struct:
				return "N" + x.Obj.Name()
			case *types.Array:
				return aggKey(x.Underlying())
			}
		case *types.Array:
			return "A" + g.typeID(x)
		}
		return ""
	}
	for _, n := range g.pkg.Types {
		st, ok := n.Underlying().(*types.Struct)
		if !ok {
			continue
		}
		nd := &node{key: "N" + n.Obj.Name()}
		var d strings.Builder
		fmt.Fprintf(&d, "struct %s {\n", g.cType(n))
		for _, f := range st.Fields {
			fmt.Fprintf(&d, "    %s %s;\n", g.cType(f.Type), cIdent(f.Name))
			if k := aggKey(f.Type); k != "" {
				nd.deps = append(nd.deps, k)
			}
		}
		if len(st.Fields) == 0 {
			d.WriteString("    char _empty;\n")
		}
		d.WriteString("}")
		if st.Packed {
			d.WriteString(" __attribute__((packed))")
		}
		if st.Align > 0 {
			fmt.Fprintf(&d, " __attribute__((aligned(%d)))", st.Align)
		}
		d.WriteString(";\n")
		nd.def = d.String()
		nodes[nd.key] = nd
	}
	for _, id := range arrIDs {
		a := g.arrays[id]
		nd := &node{key: "A" + id}
		if k := aggKey(a.Elem); k != "" {
			nd.deps = append(nd.deps, k)
		}
		n := a.Len
		if n == 0 {
			n = 1 // C has no zero-length arrays; length is tracked by the type
		}
		nd.def = fmt.Sprintf("struct gocpy_arr_%s { %s a[%d]; };\n", id, g.cType(a.Elem), n)
		nodes[nd.key] = nd
	}
	for _, id := range tupIDs {
		t := g.tuples[id]
		nd := &node{key: "T" + id}
		var d strings.Builder
		fmt.Fprintf(&d, "struct gocpy_tup_%s {", id)
		for i, v := range t.Vars {
			fmt.Fprintf(&d, " %s r%d;", g.cType(v.Type()), i)
			if k := aggKey(v.Type()); k != "" {
				nd.deps = append(nd.deps, k)
			}
		}
		d.WriteString(" };\n")
		nd.def = d.String()
		nodes[nd.key] = nd
	}
	done := map[string]int{} // 1 visiting, 2 done
	var visit func(k string)
	visit = func(k string) {
		nd := nodes[k]
		if nd == nil || done[k] == 2 {
			return
		}
		if done[k] == 1 {
			g.errs = append(g.errs, fmt.Sprintf("invalid recursive type %s (contains itself by value)", strings.TrimPrefix(k, "N")))
			return
		}
		done[k] = 1
		for _, d := range nd.deps {
			visit(d)
		}
		done[k] = 2
		b.WriteString(nd.def)
	}
	keys := make([]string, 0, len(nodes))
	for k := range nodes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		visit(k)
	}
	b.WriteString("\n")
	b.WriteString(protos.String())
	b.WriteString("\n")
	b.WriteString(inlineBodies)
	b.WriteString("#endif\n")
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

func (g *gen) attrs(f *types.Func) string {
	var a []string
	as := f.Decl.Annots
	if as.Has("noinline") {
		a = append(a, "noinline")
	}
	if as.Has("hot") {
		a = append(a, "hot")
	}
	if as.Has("cold") {
		a = append(a, "cold")
	}
	if len(a) == 0 {
		return ""
	}
	return "__attribute__((" + strings.Join(a, ", ") + ")) "
}

func (g *gen) resultType(sig *types.Signature) string {
	switch len(sig.Results) {
	case 0:
		return "void"
	case 1:
		return g.cType(sig.Results[0].Type())
	}
	return g.cType(&types.Tuple{Vars: sig.Results})
}

// signature renders a C prototype; parameter names are the Gocpy names
// (boxed parameters get a _p suffix and are copied in the prologue).
func (g *gen) signature(f *types.Func) string {
	sig := f.Sig()
	var ps []string
	if sig.Recv != nil {
		ps = append(ps, g.cType(sig.Recv.Type())+" "+g.paramName(sig.Recv))
	}
	for _, p := range sig.Params {
		ps = append(ps, g.cType(p.Type())+" "+g.paramName(p))
	}
	if len(ps) == 0 {
		ps = []string{"void"}
	}
	return fmt.Sprintf("%s %s(%s)", g.resultType(sig), f.CName, strings.Join(ps, ", "))
}

func (g *gen) paramName(v *types.Var) string {
	n := cIdent(v.Name())
	if n == "" || n == "_" {
		return "_unused_" + strconv.FormatUint(uintptrOf(v), 10)
	}
	if v.Boxed {
		return n + "_p"
	}
	return n
}

var ptrIDs = map[*types.Var]uint64{}

func uintptrOf(v *types.Var) uint64 {
	if id, ok := ptrIDs[v]; ok {
		return id
	}
	id := uint64(len(ptrIDs) + 1)
	ptrIDs[v] = id
	return id
}

// ---------------------------------------------------------------- functions

func (g *gen) line(format string, args ...any) {
	g.w.WriteString(strings.Repeat("    ", g.ind))
	fmt.Fprintf(g.w, format, args...)
	g.w.WriteByte('\n')
}

func (g *gen) funcDef(out *strings.Builder, fn *types.Func, inline bool) {
	g.sig = fn.Sig()
	g.names = map[string]int{}
	g.taken = map[string]bool{}
	g.loops = nil
	g.w = out
	g.ind = 0
	sig := fn.Sig()
	prefix := g.attrs(fn)
	if inline {
		prefix = "static inline __attribute__((always_inline)) "
	}
	g.line("%s%s {", prefix, g.signature(fn))
	params := sig.Params
	if sig.Recv != nil {
		params = append([]*types.Var{sig.Recv}, params...)
	}
	g.emitBody(sig, params, fn.Decl.Body, nil)
}

func (g *gen) declLocal(v *types.Var, init string) {
	name := g.localName(v)
	ct := g.cType(v.Type())
	if v.Boxed {
		g.line("%s *%s = (%s *)gocpy_alloc(sizeof(%s));", ct, name, ct, ct)
		g.line("*%s = %s;", name, init)
		return
	}
	g.line("%s %s = %s;", ct, name, init)
}

func (g *gen) initFunc(b *strings.Builder) {
	g.w = b
	g.ind = 0
	g.names = map[string]int{}
	g.taken = map[string]bool{}
	g.sig = &types.Signature{}
	g.excStack, g.finStack = nil, nil
	g.line("void %s_init(void) {", g.pfx)
	g.ind++
	for _, f := range g.pkg.Files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.VAR {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				g.assignSpec(vs, true)
			}
		}
	}
	g.ind--
	g.line("}")
	g.line("")
}

// assignSpec initializes variables of a var spec (global or local).
func (g *gen) assignSpec(vs *ast.ValueSpec, global bool) {
	vars := make([]*types.Var, len(vs.Names))
	for i, n := range vs.Names {
		if v, ok := g.info.Defs[n].(*types.Var); ok {
			vars[i] = v
		}
	}
	emit := func(v *types.Var, val string) {
		if v == nil || v.Name() == "_" {
			if val != "" {
				g.line("(void)(%s);", val)
			}
			return
		}
		if global {
			if val != "" {
				g.line("%s = %s;", v.CName, val)
			}
			return
		}
		if val == "" {
			val = g.zero(v.Type())
		}
		g.declLocal(v, val)
	}
	switch {
	case len(vs.Values) == 0:
		for _, v := range vars {
			emit(v, "")
		}
	case len(vs.Values) == 1 && len(vars) > 1:
		t := g.newTmp()
		g.line("%s %s = %s;", g.cType(g.typeOf(vs.Values[0])), t, g.expr(vs.Values[0]))
		for i, v := range vars {
			emit(v, fmt.Sprintf("%s.r%d", t, i))
		}
	default:
		for i, v := range vars {
			emit(v, g.expr(vs.Values[i]))
		}
	}
}

// ---------------------------------------------------------------- literals

func cString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\t':
			b.WriteString(`\t`)
		case c >= 0x20 && c < 0x7f && c != '?':
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func (g *gen) constLit(v constant.Value, t types.Type) string {
	t = types.Default(t)
	b, ok := t.Underlying().(*types.Basic)
	if !ok {
		return g.zero(t)
	}
	var s string
	switch {
	case b.IsBoolean():
		s = strconv.FormatBool(constant.BoolVal(v))
	case b.IsString():
		s = "GOCPY_STR(" + cString(constant.StringVal(v)) + ")"
	case b.IsInteger():
		iv := constant.ToInt(v)
		if b.IsUnsigned() {
			u, _ := constant.Uint64Val(iv)
			s = fmt.Sprintf("UINT64_C(%d)", u)
		} else {
			n, _ := constant.Int64Val(iv)
			if n == math.MinInt64 {
				s = "INT64_MIN"
			} else {
				s = fmt.Sprintf("INT64_C(%d)", n)
			}
		}
	case b.IsFloat():
		f, _ := constant.Float64Val(constant.ToFloat(v))
		s = strconv.FormatFloat(f, 'g', 17, 64)
		if !strings.ContainsAny(s, ".e") {
			s += ".0"
		}
	}
	ct := g.cType(t)
	if ct == "int64_t" || ct == "uint64_t" || ct == "bool" || ct == "double" || ct == "gocpy_string" {
		return s
	}
	return "((" + ct + ")" + s + ")"
}
